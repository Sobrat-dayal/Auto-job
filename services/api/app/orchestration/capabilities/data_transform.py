"""Data transformation capability for dictionary merging, filtering, and report generation."""

import json
from typing import Any

from app.orchestration.capabilities.base import BaseCapability
from app.orchestration.contracts import VerificationPolicy


class DataTransformCapability(BaseCapability):
    """Performs deterministic schema transformations and markdown report compilation."""

    capability_id = "data_transform"
    name = "Data Transformation"
    version = "1.0.0"
    description = "Transforms, merges, filters data dictionaries and formats structured executive markdown reports."
    requires_ai = False
    is_deterministic = True
    default_verification_policy = VerificationPolicy.SCHEMA_VALIDATION
    timeout_seconds = 30
    idempotent = True

    @property
    def input_schema(self) -> dict[str, Any]:
        return {
            "type": "object",
            "properties": {
                "operation": {
                    "type": "string",
                    "enum": ["merge", "filter", "format_markdown_report", "flatten", "key_map"],
                    "default": "format_markdown_report",
                },
                "data": {"type": "object"},
                "parameters": {"type": "object"},
            },
            "required": ["data"],
        }

    @property
    def output_schema(self) -> dict[str, Any]:
        return {
            "type": "object",
            "properties": {
                "transformed_data": {"type": "object"},
                "status": {"type": "string"},
                "operation": {"type": "string"},
            },
            "required": ["transformed_data", "status", "operation"],
        }

    async def execute(
        self,
        input_data: dict[str, Any],
        context: dict[str, Any] | None = None,
    ) -> dict[str, Any]:
        op = input_data.get("operation", "format_markdown_report")
        data = input_data.get("data", {})
        params = input_data.get("parameters", {})

        if not isinstance(data, dict):
            data = {"raw_value": data}

        if op == "format_markdown_report":
            report_title = params.get("title", data.get("title", "Job Analysis Report"))
            job_title = data.get("job_title", "Software Engineering Role")
            summary = data.get("summary", "")
            skills = data.get("skills", data.get("technical_skills", []))
            experience = data.get("experience", data.get("experience_years", "Not specified"))
            responsibilities = data.get("responsibilities", [])

            lines = [
                f"# {report_title}",
                "",
                f"**Role**: {job_title}",
                f"**Experience Requirement**: {experience}",
                "",
                "## Executive Summary",
                summary if summary else "No summary provided.",
                "",
                "## Technical Skills & Proficiencies",
            ]
            if isinstance(skills, list) and skills:
                for skill in skills:
                    lines.append(f"- **{skill}**")
            elif isinstance(skills, str):
                lines.append(skills)
            else:
                lines.append("- General software engineering stack")

            lines.append("")
            lines.append("## Core Responsibilities")
            if isinstance(responsibilities, list) and responsibilities:
                for resp in responsibilities:
                    lines.append(f"- {resp}")
            elif isinstance(responsibilities, str):
                lines.append(responsibilities)
            else:
                lines.append("- Core development and maintenance.")

            lines.append("")
            lines.append("---")
            lines.append("*Generated by AUTONOM Multi-Agent Orchestrator (Stage 12)*")

            report_md = "\n".join(lines)
            return {
                "transformed_data": {
                    "report_markdown": report_md,
                    "title": report_title,
                    "section_count": 4,
                },
                "status": "success",
                "operation": op,
            }

        elif op == "merge":
            secondary = params.get("secondary", {})
            merged = {**data, **secondary}
            return {
                "transformed_data": merged,
                "status": "success",
                "operation": op,
            }

        elif op == "filter":
            allow_keys = set(params.get("keys", []))
            filtered = {k: v for k, v in data.items() if k in allow_keys}
            return {
                "transformed_data": filtered,
                "status": "success",
                "operation": op,
            }

        elif op == "flatten":
            flat: dict[str, Any] = {}
            def _flat(obj: dict[str, Any], prefix: str = "") -> None:
                for k, v in obj.items():
                    key = f"{prefix}.{k}" if prefix else k
                    if isinstance(v, dict):
                        _flat(v, key)
                    else:
                        flat[key] = v
            _flat(data)
            return {
                "transformed_data": flat,
                "status": "success",
                "operation": op,
            }

        return {
            "transformed_data": data,
            "status": "unmodified",
            "operation": op,
        }
